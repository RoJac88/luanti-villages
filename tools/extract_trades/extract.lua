-- Regenerates trade_tables.lua from an installed VoxeLibre's villager trade tables, which
-- mobs_mc/villager.lua keeps in a file-local `professions` table nothing else can read.
-- The table only refers to N (the translator) and E1 (one emerald), so its source is cut
-- out and evaluated here with those two stubbed: no engine is needed.
--
--   luajit tools/extract_trades/extract.lua [path/to/mobs_mc/villager.lua] [version] > trade_tables.lua
--
-- Rerun it when the supported VoxeLibre version changes.
local path = arg[1] or (os.getenv("HOME") .. "/.minetest/games/mineclone2/mods/ENTITIES/mobs_mc/villager.lua")
local version = arg[2] or "0.92.3"

local handle = assert(io.open(path, "r"), "cannot read " .. path)
local source = handle:read("*a")
handle:close()

-- From `local professions = {` to the `}` that closes it, counting braces outside strings
-- and comments.
local start = assert(source:find("\nlocal professions = {", 1, true), "no professions table in " .. path) + 1
local open = source:find("{", start, true)
local depth, i, finish = 0, open, nil
while i <= #source do
	local c = source:sub(i, i)
	if c == "-" and source:sub(i, i + 1) == "--" then
		i = (source:find("\n", i, true) or #source) - 1
	elseif c == '"' or c == "'" then
		local j = i + 1
		while source:sub(j, j) ~= c do
			if source:sub(j, j) == "\\" then j = j + 1 end
			j = j + 1
		end
		i = j
	elseif c == "{" then
		depth = depth + 1
	elseif c == "}" then
		depth = depth - 1
		if depth == 0 then finish = i break end
	end
	i = i + 1
end
assert(finish, "unbalanced professions table")

local chunk = assert(loadstring("return " .. source:sub(open, finish)))
setfenv(chunk, {N = function(text) return text end, E1 = {"mcl_core:emerald", 1, 1}})
local professions = chunk()

-- One ingredient list: {item, min, max} or {item, min, max, item2, min2, max2}.
local function spec(list)
	local out = {}
	for k = 1, #list, 3 do out[#out + 1] = {item = list[k], min = list[k + 1], max = list[k + 2]} end
	return out
end

local names = {}
for name in pairs(professions) do names[#names + 1] = name end
table.sort(names)

local lines = {
	"-- VoxeLibre " .. version .. "'s villager trade tables (mobs_mc/villager.lua `professions`), one",
	"-- entry per trade: its tier, what the villager wants and what it offers, each item with",
	"-- the count range vanilla rolls from. Generated by tools/extract_trades/extract.lua; do not",
	"-- edit. ledger.lua derives the economy's base prices from it.",
	"return {",
	("\tversion = %q,"):format(version),
	"\tprofessions = {",
}
local function format_spec(items)
	local parts = {}
	for _, s in ipairs(items) do
		parts[#parts + 1] = ("{item = %q, min = %d, max = %d}"):format(s.item, s.min, s.max)
	end
	return "{" .. table.concat(parts, ", ") .. "}"
end
for _, name in ipairs(names) do
	local profession = professions[name]
	lines[#lines + 1] = ("\t\t%s = {"):format(name)
	if profession.jobsite then lines[#lines + 1] = ("\t\t\tjobsite = %q,"):format(profession.jobsite) end
	lines[#lines + 1] = "\t\t\ttrades = {"
	for tier, trades in ipairs(profession.trades or {}) do
		for _, trade in ipairs(trades) do
			lines[#lines + 1] = ("\t\t\t\t{tier = %d, wanted = %s, offered = %s},"):format(
				tier, format_spec(spec(trade[1])), format_spec(spec(trade[2])))
		end
	end
	lines[#lines + 1] = "\t\t\t},"
	lines[#lines + 1] = "\t\t},"
end
lines[#lines + 1] = "\t},"
lines[#lines + 1] = "}"
io.write(table.concat(lines, "\n"), "\n")
